/**
 * Config plugin: Android HTTP recovers from a network change without relaunching the app.
 *
 * Why:
 *   React Native's fetch on Android (OkHttp) keeps reusing pooled connections opened on a
 *   network that is gone (Wi-Fi ↔ mobile data, a drop, airplane mode). Every request then
 *   hangs until our 15 s timeout, even once the phone is back online, until the app is
 *   relaunched: "Couldn't load cities", a Today stuck loading. Reproduced on the emulator
 *   (network off/on while the app runs) on 2026-10-29.
 *
 * What it adds (MainApplication.onCreate):
 *   - every OkHttp client RN creates pings its HTTP/2 connections every 15 s, so a dead
 *     one is closed (and its requests fail fast, then retried) instead of hanging;
 *   - on a network change (a new default network, or the current one lost), idle pooled
 *     connections are evicted, so the next request opens a fresh one on the new network.
 */
const fs = require('fs');
const path = require('path');
const { withDangerousMod, withMainApplication } = require('@expo/config-plugins');

const KOTLIN = (pkg) => `package ${pkg}

import android.content.Context
import android.net.ConnectivityManager
import android.net.Network
import com.facebook.react.modules.network.OkHttpClientFactory
import com.facebook.react.modules.network.OkHttpClientProvider
import java.lang.ref.WeakReference
import java.util.concurrent.TimeUnit
import okhttp3.OkHttpClient

// Generated by plugins/withNetworkRecovery.js: see there why.
object NetworkRecovery {
  private val clients = mutableListOf<WeakReference<OkHttpClient>>()

  fun install(context: Context) {
    val app = context.applicationContext
    OkHttpClientProvider.setOkHttpClientFactory(OkHttpClientFactory {
      OkHttpClientProvider.createClientBuilder(app)
        .pingInterval(15, TimeUnit.SECONDS)
        .build()
        .also { synchronized(clients) { clients.add(WeakReference(it)) } }
    })
    val cm = app.getSystemService(Context.CONNECTIVITY_SERVICE) as? ConnectivityManager ?: return
    try {
      cm.registerDefaultNetworkCallback(object : ConnectivityManager.NetworkCallback() {
        override fun onAvailable(network: Network) = evict()
        override fun onLost(network: Network) = evict()
      })
    } catch (_: Exception) { /* no callback: the ping still closes dead connections */ }
  }

  private fun evict() {
    synchronized(clients) {
      clients.removeAll { it.get() == null }
      clients.forEach { it.get()?.connectionPool?.evictAll() }
    }
  }
}
`;

module.exports = function withNetworkRecovery(config) {
  const pkg = config.android?.package ?? 'com.hilads.app';
  config = withDangerousMod(config, ['android', (config) => {
    const dir = path.join(config.modRequest.platformProjectRoot, 'app/src/main/java', ...pkg.split('.'));
    fs.mkdirSync(dir, { recursive: true });
    fs.writeFileSync(path.join(dir, 'NetworkRecovery.kt'), KOTLIN(pkg));
    return config;
  }]);
  return withMainApplication(config, (config) => {
    const src = config.modResults.contents;
    if (!src.includes('NetworkRecovery.install(this)')) {
      config.modResults.contents = src.replace(
        /super\.onCreate\(\)\n/,
        'super.onCreate()\n    NetworkRecovery.install(this) // plugins/withNetworkRecovery.js\n',
      );
    }
    return config;
  });
};
