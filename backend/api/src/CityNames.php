    /** The slug rule of the app and the web ("Ho Chi Minh City" → "ho-chi-minh-city"). */
    public static function slug(string $name): string
    {
        return trim((string) preg_replace('/[^a-z0-9]+/', '-', strtolower($name)), '-');
    }

    public static function short(?string $name, string $locale = 'en'): string
    {
        if ($name === null || $name === '') {
            return '';
        }
        $slug  = self::slug($name);
        $short = self::SHORT[$slug] ?? null;
        if ($short !== null && isset($short[$locale])) {
            return $short[$locale];
        }
        if ($short !== null && !in_array($locale, self::NON_LATIN, true)) {
            return $short['*'];
        }
        return self::LOCALIZED[$locale][$slug] ?? $name;
    }
